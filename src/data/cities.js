export function getCity(name) { return CITIES[name] || null }
export function getTransport(a, b) {
  const key1 = `${a}-${b}`, key2 = `${b}-${a}`
  const hit = TRANSPORT_MATRIX[key1] || TRANSPORT_MATRIX[key2]
  if (hit) return hit
  // 直线距离估算（高铁 ~260km/h，保底 0.5h）
  const ca = getCity(a)?.coord, cb = getCity(b)?.coord
  if (ca && cb) {
    const dLat = (cb.lat - ca.lat) * Math.PI / 180
    const dLng = (cb.lng - ca.lng) * Math.PI / 180
    const lat1 = ca.lat * Math.PI / 180, lat2 = cb.lat * Math.PI / 180
    const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2
    const km = 6371 * 2 * Math.asin(Math.sqrt(h))
    return { mode: '高铁', hours: Math.max(0.5, Math.round(km / 260 * 10) / 10), estimated: true }
  }
  return { mode: '高铁', hours: 2, estimated: true }
}

